class Solution:
    def sortArray(self, nums: List[int]) -> List[int]:
        # Bubble-sort
        swapped = True
        while swapped:
            swapped = False
            for i in range(len(nums) - 1):
                if nums[i] > nums[i + 1]:
                    nums[i], nums[i + 1] = nums[i + 1], nums[i]
                    swapped = True
        
        return nums